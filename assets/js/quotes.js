/**
 * Zieht Zitate in zufälliger Reihenfolge und beginnt erst von vorn,
 * wenn der ganze Stapel durch ist — so wiederholt sich nichts direkt.
 */
export function createQuoteDeck(pool = QUOTES) {
  let stack = [];

  const reshuffle = () => {
    stack = [...pool];
    for (let i = stack.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [stack[i], stack[j]] = [stack[j], stack[i]];
    }
  };

  return () => {
    if (!stack.length) reshuffle();
    return stack.pop();
  };
}
